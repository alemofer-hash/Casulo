WORK_RECEIPT_SCHEMA = "casulo.interlocution-work-receipt/1.0"
PRIMITIVE_SCHEMA = "casulo.interlocution-primitive/1.0"
SUPERVISOR_SCHEMA = "casulo.interlocution-worker-summary/1.0"


class WorkerDenied(RuntimeError):
    pass


@dataclass(frozen=True, slots=True)
class GovernedWorkerResult:
    summary: Mapping[str, Any]
    receipts: tuple[Mapping[str, Any], ...]
    result_file: Path


def sha256_file(path: str | Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_primitive_manifest(
    *, executable: str | Path, tcap: str | Path, source: str | Path
) -> dict[str, Any]:
    executable_path = Path(executable).resolve(strict=True)
    tcap_path = Path(tcap).resolve(strict=True)
    source_path = Path(source).resolve(strict=True)
    seed = {
        "schema": PRIMITIVE_SCHEMA,
        "name": "casulo-flood-native-full-worker",
        "version": "1.0-r2-preserved",
        "kind": "foreign_primitive",
        "decision_authority": False,
        "invocation_authority": "T",
        "abi": "casulo-learn-context-sysv64-counters/1.0",
        "executable_sha256": sha256_file(executable_path),
        "source_sha256": sha256_file(source_path),
        "kernel_tcap_sha256": sha256_file(tcap_path),
        "inputs": [
            "content-addressed dataset",
            "content-addressed initialization bundle",
            "T authority grant",
        ],
        "outputs": ["binary results", "runtime counters", "work receipts"],
        "precision": ["float64"],
        "supported_policy": {
            "records": "1024",
            "input_features": "8",
            "dtype": "float64",
            "loss": "mse",
            "optimizer": "sgd",
            "learning_rate": "0.018",
            "initialization_state_policy": "reset_each_case",
            "optimizer_state_policy": "reset_each_case",
            "working_set_policy": "all_records",
            "working_set_start": "0",
            "working_set_count": "1024",
            "stopping_policy": "fixed_epochs",
            "epochs": "400",
            "absolute_tolerance": "1e-09",
            "require_exact_counters": "true",
            "require_no_nan_inf": "true",
        },
        "effects": ["read_dataset", "read_initializations", "write_results"],
        "low_level_implementation": "Rust wrapper plus AOT x86-64 kernel generated by the preserved T/0.2 learn backend",
    }
    return {**seed, "manifest_sha256": canonical_sha256(seed)}


def validate_primitive_manifest(value: Mapping[str, Any]) -> None:
    if value.get("schema") != PRIMITIVE_SCHEMA:
        raise WorkerDenied("primitive manifest schema mismatch")
    observed = require_sha256(value.get("manifest_sha256"), "manifest_sha256")
    seed = {key: item for key, item in value.items() if key != "manifest_sha256"}
    if canonical_sha256(seed) != observed:
        raise WorkerDenied("primitive manifest seal mismatch")
    if value.get("decision_authority") is not False or value.get("invocation_authority") != "T":
        raise WorkerDenied("primitive claims forbidden decision authority")


def _load_json(path: str | Path) -> dict[str, Any]:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise WorkerDenied(f"invalid JSON artifact: {path}") from error
    if not isinstance(value, dict):
        raise WorkerDenied(f"JSON artifact is not an object: {path}")
    return value


def _validate_authority(
    grant: Mapping[str, Any], receipt_file: str | Path
) -> tuple[dict[str, str], tuple[dict[str, Any], ...]]:
    observed = require_sha256(grant.get("grant_sha256"), "grant_sha256")
    seed = {key: item for key, item in grant.items() if key != "grant_sha256"}
    if canonical_sha256(seed) != observed:
        raise WorkerDenied("authority grant seal mismatch")
    if grant.get("foreign_affirmative_fallback") is not False:
        raise WorkerDenied("authority grant permits a foreign affirmative fallback")
    config = grant.get("config_from_t")
    if not isinstance(config, dict) or not all(
        isinstance(key, str) and isinstance(value, str) for key, value in config.items()
    ):
        raise WorkerDenied("T authority config is not a text map")
    lines = Path(receipt_file).read_text(encoding="utf-8").splitlines()
    try:
        receipts = tuple(json.loads(line) for line in lines if line.strip())
    except json.JSONDecodeError as error:
        raise WorkerDenied("T authority receipt stream is invalid") from error
    if len(receipts) != 9:
        raise WorkerDenied("T authority receipt count is not nine")
    if tuple(item.get("surface_id") for item in receipts) != POLICY_SURFACES:
        raise WorkerDenied("T authority surfaces are incomplete or reordered")
    if list(grant.get("receipt_chain", [])) != [item.get("receipt_hash") for item in receipts]:
        raise WorkerDenied("authority grant does not bind the receipt stream")
    previous = "0" * 64
    for receipt in receipts:
        if receipt.get("schema") != "casulo.t-decision-receipt/2.0":
            raise WorkerDenied("T authority receipt schema mismatch")
        if receipt.get("tcap_hash") != grant.get("tcap_hash"):
            raise WorkerDenied("T authority receipt references another TCAP")
        if receipt.get("previous_receipt_hash") != previous:
            raise WorkerDenied("T authority receipt chain is broken")
        if receipt.get("result") != "ok":
            raise WorkerDenied("T authority receipt is not affirmative")
        receipt_hash = require_sha256(receipt.get("receipt_hash"), "receipt_hash")
        receipt_seed = {key: item for key, item in receipt.items() if key != "receipt_hash"}
        if canonical_sha256(receipt_seed) != receipt_hash:
            raise WorkerDenied("T authority receipt hash mismatch")
        previous = receipt_hash
    return dict(config), receipts


def _runtime_counter_hash(result: CaseResult) -> str:
    return canonical_sha256(
        {
            "epochs_completed": result.epochs_completed,
            "forward_epochs": result.forward_epochs,
            "backward_epochs": result.backward_epochs,
            "optimizer_steps": result.optimizer_steps,
            "records_visited": result.records_visited,
            "parameter_writes": result.parameter_writes,
        }
    )


def _result_receipt(
    *,
    result: CaseResult,
    dataset_sha256: str,
    initialization_sha256: str,
    authority_receipt_hash: str,
    primitive_sha256: str,
    result_file_sha256: str,
    child_timing: Mapping[str, int],
    previous_chain_hash: str,
) -> tuple[dict[str, Any], str]:
    parameters = struct.pack(f"<{len(result.parameters)}d", *result.parameters)
    predictions = struct.pack(f"<{len(result.predictions)}d", *result.predictions)
    seed = {
        "schema": WORK_RECEIPT_SCHEMA,
        "work_unit_id": "flood-surrogate-full-v1",
        "case_id": f"case-{result.case_id:04d}",
        "case_index": result.index,
        "nonce": result.nonce.hex(),
        "seed": result.seed,
        "dataset_hash": dataset_sha256,
        "initialization_bundle_hash": initialization_sha256,
        "epochs_completed": result.epochs_completed,
        "forward_epochs": result.forward_epochs,
        "backward_epochs": result.backward_epochs,
        "optimizer_steps": result.optimizer_steps,
        "records_visited": result.records_visited,
        "parameter_writes": result.parameter_writes,
        "final_loss": result.final_loss,
        "final_parameters_hash": hashlib.sha256(parameters).hexdigest(),
        "predictions_hash": hashlib.sha256(predictions).hexdigest(),
        "runtime_counter_hash": _runtime_counter_hash(result),
        "authority_receipt_hash": authority_receipt_hash,
        "primitive_manifest_sha256": primitive_sha256,
        "result_file_sha256": result_file_sha256,
        "child_timing": dict(child_timing),
        "previous_work_chain_hash": previous_chain_hash,
    }
    receipt_hash = canonical_sha256(seed)
    chain_hash = hashlib.sha256(
        bytes.fromhex(previous_chain_hash) + bytes.fromhex(receipt_hash)
    ).hexdigest()
    return {**seed, "receipt_hash": receipt_hash, "chain_hash": chain_hash}, chain_hash


def run_governed_worker(
    *,
    grant_file: str | Path,
    authority_receipt_file: str | Path,
    primitive_manifest_file: str | Path,
    executable: str | Path,
    dataset: str | Path,
    initializations: str | Path,
    output_directory: str | Path,
    start: int = 0,
    count: int = 1,
) -> GovernedWorkerResult:
    output = Path(output_directory).resolve()
    if output.exists():
        raise WorkerDenied("governed worker output already exists")
    output.mkdir(parents=True)
    grant = _load_json(grant_file)
    primitive = _load_json(primitive_manifest_file)
    validate_primitive_manifest(primitive)
    config, authority_receipts = _validate_authority(grant, authority_receipt_file)
    if config != primitive.get("supported_policy") | {
        "dataset_sha256": config.get("dataset_sha256", ""),
        "bundle_sha256": config.get("bundle_sha256", ""),
    }:
        # Dataset and initialization identities are runtime-bound; every other
        # field must be exactly supported by the primitive. No substitution.
        policy = {
            key: value
            for key, value in config.items()
            if key not in {"dataset_sha256", "bundle_sha256"}
        }
        if policy != primitive.get("supported_policy"):
            raise WorkerDenied("T policy is not supported by the primitive ABI")
    executable_path = Path(executable).resolve(strict=True)
    dataset_path = Path(dataset).resolve(strict=True)
    initialization_path = Path(initializations).resolve(strict=True)
    if sha256_file(executable_path) != primitive["executable_sha256"]:
        raise WorkerDenied("primitive executable hash mismatch")
    dataset_sha256 = sha256_file(dataset_path)
    initialization_sha256 = sha256_file(initialization_path)
    if dataset_sha256 != config.get("dataset_sha256"):
        raise WorkerDenied("dataset changed after T authorization")
    if initialization_sha256 != config.get("bundle_sha256"):
        raise WorkerDenied("initialization changed after T authorization")
    if count < 1 or start < 0:
        raise WorkerDenied("invalid governed work range")

    result_file = output / "worker-result.bin"
    command = [
        str(executable_path),
        str(dataset_path),
        str(initialization_path),
        str(start),
        str(count),
        str(result_file),
    ]
    parent_start = time.perf_counter_ns()
    process = subprocess.run(
        command,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=max(60.0, count * 2.0),
        check=False,
        env={**os.environ, "OMP_NUM_THREADS": "1", "MKL_NUM_THREADS": "1"},
    )
    parent_ns = time.perf_counter_ns() - parent_start
    if process.returncode != 0 or not result_file.is_file():
        raise WorkerDenied(
            f"foreign primitive failed closed: rc={process.returncode} stderr={process.stderr.strip()}"
        )
    fields = process.stdout.strip().split()
    if len(fields) != 7 or fields[0] != "RESULT":
        raise WorkerDenied("foreign primitive timing envelope is invalid")
    child_timing = {
        "start": int(fields[1]),
        "count": int(fields[2]),
        "worker_monotonic_ns": int(fields[3]),
        "qpc_ticks": int(fields[4]),
        "qpc_frequency": int(fields[5]),
        "thread_cycles": int(fields[6]),
        "parent_monotonic_ns": parent_ns,
    }
    results = parse_result_file(result_file)
    if len(results) != count:
        raise WorkerDenied("primitive completed count differs from requested work")
    result_hash = sha256_file(result_file)
    receipts: list[dict[str, Any]] = []
    previous_chain = "0" * 64
    for result in results:
        receipt, previous_chain = _result_receipt(
            result=result,
            dataset_sha256=dataset_sha256,
            initialization_sha256=initialization_sha256,
            authority_receipt_hash=str(authority_receipts[-1]["receipt_hash"]),
            primitive_sha256=str(primitive["manifest_sha256"]),
            result_file_sha256=result_hash,
            child_timing=child_timing,
            previous_chain_hash=previous_chain,
        )
        receipts.append(receipt)
    receipt_path = output / "work-receipts.jsonl"
    receipt_path.write_text(
        "".join(
            json.dumps(item, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
            + "\n"
            for item in receipts
        ),
        encoding="utf-8",
        newline="\n",
    )
    summary_seed = {
        "schema": SUPERVISOR_SCHEMA,
        "status": "WORK_COMPLETED_RECEIPTED",
        "K_requested": count,
        "K_started": count,
        "K_completed": len(receipts),
        "epochs_completed": sum(item["epochs_completed"] for item in receipts),
        "optimizer_steps": sum(item["optimizer_steps"] for item in receipts),
        "records_visited": sum(item["records_visited"] for item in receipts),
        "parameter_writes": sum(item["parameter_writes"] for item in receipts),
        "authority_chain_tip": authority_receipts[-1]["receipt_hash"],
        "work_chain_tip": previous_chain,
        "receipt_file_sha256": sha256_file(receipt_path),
        "result_file_sha256": result_hash,
        "child_timing": child_timing,
    }
    summary = {**summary_seed, "summary_sha256": canonical_sha256(summary_seed)}
    (output / "worker-summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return GovernedWorkerResult(summary, tuple(receipts), result_file)

